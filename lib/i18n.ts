function matchLocale(language: string): Locale | null {
  const normalized = language.trim().replaceAll('_', '-').toLowerCase();
  const exact = SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === normalized);
  if (exact) return exact;
  if (normalized.startsWith('pt')) return 'pt-BR';
  if (normalized.startsWith('zh')) return 'zh-CN';
  const base = normalized.split('-')[0];
  return SUPPORTED_LOCALES.find((locale) => locale.toLowerCase() === base) ?? null;
}

export function t(
  locale: Locale,
  key: MessageKey,
  replacements: Record<string, string | number> = {},
): string {
  return Object.entries(replacements).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function resolveLocale(
  setting: Locale | 'auto',
  documentLanguage = 'en',
  browserLanguages: readonly string[] = [],
): Locale {
  if (setting !== 'auto') return setting;
  for (const language of [documentLanguage, ...browserLanguages]) {
    const matched = matchLocale(language);
    if (matched) return matched;
  }
  return 'en';
}

export function localeTag(locale: Locale): string {
  return localeTags[locale];
}

export function localeDirection(locale: Locale): 'ltr' | 'rtl' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function weekdayLabels(locale: Locale): string[] {
  const formatter = new Intl.DateTimeFormat(localeTag(locale), { weekday: 'narrow' });
  return Array.from({ length: 7 }, (_, day) =>
    formatter.format(new Date(2024, 0, 7 + day, 12)),
  );
}
